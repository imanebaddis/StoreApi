-- Categorie dei libri (attività 2.1) e legame libro-categoria (attività 3.1).
-- Eseguire una sola volta dopo 001_books.sql e 002_profiles.sql, verificando prima il progetto Supabase.
-- Lo schema store resta privato: l'accesso passa soltanto dall'API.
create table store.categories (
    id integer generated by default as identity primary key,
    name text not null check (length(trim(name)) between 1 and 80),
    description text check (description is null or length(description) <= 500),
    created_at timestamptz not null default now()
);

-- Nomi unici senza distinzione tra maiuscole e minuscole né spazi iniziali/finali.
create unique index categories_name_unique on store.categories (lower(trim(name)));

alter table store.categories enable row level security;
revoke all on store.categories from anon, authenticated;

-- Eliminando una categoria i libri restano nel catalogo senza categoria.
alter table store.books
    add column if not exists category_id integer references store.categories(id) on delete set null;
create index if not exists books_category_id_idx on store.books (category_id);

-- Categorie iniziali, coerenti con il prototipo frontend.
insert into store.categories (name, description) values
    ('Narrativa', 'Romanzi e racconti.'),
    ('Classici', 'Opere che hanno attraversato le generazioni.'),
    ('Saggi', 'Riflessioni, storia e idee.'),
    ('Scienza', 'Divulgazione scientifica.')
on conflict do nothing;
